/**
 * A ferrofluid display: a dish of glossy black magnetic fluid that rises into spikes - with a redstone signal (the
 * stronger, the taller), or with music playing nearby (the bass in the middle, the treble round the edge) - and settles
 * back into a gently heaving pool (client/FerrofluidRenderer).
 */
public class FerrofluidBlock extends BaseEntityBlock {
    public static final MapCodec<FerrofluidBlock> CODEC = simpleCodec(FerrofluidBlock::new);
    private static final VoxelShape SHAPE = Shapes.or(Block.box(3, 0, 3, 13, 2.5, 13), Block.box(1.5, 2.5, 1.5, 14.5, 5, 14.5));

    public FerrofluidBlock(Properties properties) {
        super(properties);
    }

    @Override
    protected MapCodec<? extends BaseEntityBlock> codec() {
        return CODEC;
    }

    @Override
    protected RenderShape getRenderShape(BlockState state) {
        return RenderShape.MODEL;
    }

    @Override
    protected VoxelShape getShape(BlockState state, BlockGetter level, BlockPos pos, CollisionContext context) {
        return SHAPE;
    }

    @Nullable
    @Override
    public BlockEntity newBlockEntity(BlockPos pos, BlockState state) {
        return new SimpleRenderedBlockEntity(ModBlockEntities.FERROFLUID.get(), pos, state);
    }

    @Override
    public void appendHoverText(ItemStack stack, Item.TooltipContext context, List<Component> tooltip, TooltipFlag flag) {
        tooltip.add(Component.translatable("tooltip.skyblocks.ferrofluid").withStyle(ChatFormatting.GRAY));
    }
}
